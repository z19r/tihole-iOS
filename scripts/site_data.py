#!/usr/bin/env python3
"""Writes site/src/data.js from project.yml and CHANGELOG.md.

Usage: site_data.py

The site shows the app version and a release feed. Both come from the repo,
so this script turns them into one script file the page loads. Netlify runs
it as the site's build command; data.js is not checked in.
"""

import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "site" / "src" / "data.js"


def version():
    text = (ROOT / "project.yml").read_text()
    return re.search(r'MARKETING_VERSION:\s*"?([\d.]+)', text).group(1)


def changelog():
    releases, release, section = [], None, None
    for line in (ROOT / "CHANGELOG.md").read_text().splitlines():
        heading = re.match(r"## \[([\d.]+)\] - (\S+)", line)
        if heading:
            release = {"ver": heading[1], "date": heading[2], "sections": []}
            releases.append(release)
            section = None
        elif line.startswith("## "):
            release = None
        elif release and line.startswith("### "):
            section = {"name": line[4:].strip().lower(), "bullets": []}
            release["sections"].append(section)
        elif section and line.startswith("- "):
            section["bullets"].append(line[2:].strip())
        elif section and line.startswith("  ") and section["bullets"]:
            section["bullets"][-1] += " " + line.strip()
    return releases


def render():
    data = {"version": version(), "changelog": changelog()}
    return (
        "// Generated by scripts/site_data.py from project.yml and"
        " CHANGELOG.md.\n"
        "// Do not edit; run `just site-data`.\n"
        f"window.TIHOLE_DATA = {json.dumps(data, indent=2)};\n"
    )


def main():
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render())
    print(OUT)


if __name__ == "__main__":
    main()
